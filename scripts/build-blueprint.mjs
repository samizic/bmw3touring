#!/usr/bin/env node
// Converts the Dimensions.com BMW 3 Series Touring drawing (SVG) into restyled linework
// for src/components/Blueprint.astro. Only the car geometry is kept; the original
// dimension annotations, colours and stroke styling are dropped.
//
// Source: https://www.dimensions.com/element/bmw-3-series-touring-g21-7th-gen
// Licence: non-commercial use with attribution and a link back (see the figure caption).
//
// Usage: node scripts/build-blueprint.mjs path/to/Dimensions-BMW-3-Series-Touring.svg
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2] ?? '', 'utf8');

// Layers in the source file -> our line classes
const LAYERS = {
  '_x32_D_x24_AG-OUTLINE': 'o', // body outline of each view
  '_x32_D_x24_AG-TRANSPORT': 't', // panel lines
  '_x32_D_x24_AG-DETAILS': 'd', // fine details
};

// Views are laid out in four quadrants of the 1000 x 675 sheet
const viewOf = (x, y) => (y < 300 ? (x < 665 ? 'side' : 'front') : x < 665 ? 'plan' : 'rear');

const out = { side: {}, front: {}, plan: {}, rear: {} };
for (const v of Object.values(out)) for (const c of Object.values(LAYERS)) v[c] = [];

for (const [id, cls] of Object.entries(LAYERS)) {
  const start = src.indexOf(`<g id="${id}"`);
  if (start < 0) throw new Error(`Layer ${id} not found`);
  // Layer ends where the next top-level layer starts
  const nextStarts = Object.keys(LAYERS)
    .concat('_x32_D_x24_AG-DIAGRAM', 'N-DIMENSIONS')
    .map((k) => src.indexOf(`<g id="${k}"`))
    .filter((i) => i > start);
  const end = nextStarts.length ? Math.min(...nextStarts) : src.length;
  const chunk = src.slice(start, end);

  for (const m of chunk.matchAll(/<(path|line|polyline|polygon)\b([^>]*?)\/?>/g)) {
    const [, tag, attrs] = m;
    const get = (a) => attrs.match(new RegExp(`\\s${a}="([^"]*)"`))?.[1];
    let el, x, y;
    if (tag === 'path') {
      const d = get('d');
      [x, y] = d.match(/-?\d*\.?\d+/g).map(Number);
      el = `<path d="${d}"/>`;
    } else if (tag === 'line') {
      const [x1, y1, x2, y2] = ['x1', 'y1', 'x2', 'y2'].map(get);
      [x, y] = [Number(x1), Number(y1)];
      el = `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`;
    } else {
      const pts = get('points');
      [x, y] = pts.match(/-?\d*\.?\d+/g).map(Number);
      el = `<${tag} points="${pts}"/>`;
    }
    out[viewOf(x, y)][cls].push(el);
  }
}

const body = Object.entries(out)
  .map(([view, layers]) =>
    `  ${view}: {\n` +
    Object.entries(layers).map(([c, els]) => `    ${c}: ${JSON.stringify(els.join(''))},`).join('\n') +
    `\n  },`,
  )
  .join('\n');

writeFileSync(
  'src/data/blueprint-g21.ts',
  `// GENERATED by scripts/build-blueprint.mjs, do not edit by hand.\n` +
    `// Linework adapted from Dimensions.com (https://www.dimensions.com/element/bmw-3-series-touring-g21-7th-gen),\n` +
    `// used non-commercially with attribution. o = outline, t = panel lines, d = details.\n` +
    `export const linework = {\n${body}\n} as const;\n`,
);

for (const [v, l] of Object.entries(out)) console.log(v, Object.fromEntries(Object.entries(l).map(([c, e]) => [c, e.length])));
